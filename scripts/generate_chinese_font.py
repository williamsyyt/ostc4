#!/usr/bin/env python3
"""Generate an OSTC4 sparse 8-bpp, column-major Chinese bitmap font."""

import argparse
import math
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont


def parse_args():
    parser = argparse.ArgumentParser()
    parser.add_argument("--font", required=True, type=Path, help="Licensed CJK OTF/TTF font")
    parser.add_argument("--output", required=True, type=Path, help="Generated C header")
    parser.add_argument("--characters", default="语言简体中文")
    parser.add_argument("--font-size", type=int, default=48)
    parser.add_argument("--height", type=int, default=56)
    parser.add_argument("--name", default="FontT48Chinese")
    return parser.parse_args()


def render_glyph(font, character, height):
    left, top, right, bottom = font.getbbox(character)
    glyph_width = right - left
    glyph_height = bottom - top
    if glyph_width <= 0 or glyph_height <= 0 or glyph_height > height:
        raise ValueError(f"Invalid glyph dimensions for U+{ord(character):04X}: {font.getbbox(character)}")

    width = max(1, math.ceil(font.getlength(character)))
    if width < glyph_width:
        width = glyph_width
    image = Image.new("L", (width, height), 0)
    draw = ImageDraw.Draw(image)
    x = (width - glyph_width) // 2 - left
    y = (height - glyph_height) // 2 - top
    draw.text((x, y), character, font=font, fill=255)

    data = []
    pixels = image.load()
    for column in range(width):
        values = [pixels[column, row] for row in range(height)]
        if any(values):
            data.extend(values)
        else:
            data.append(1)  # OSTC4 empty-column marker
    return width, data, image


def format_bytes(data):
    lines = []
    for offset in range(0, len(data), 16):
        chunk = data[offset:offset + 16]
        lines.append("    " + ", ".join(f"0x{value:02X}" for value in chunk) + ",")
    return "\n".join(lines)


def main():
    args = parse_args()
    if args.height <= 0 or args.height % 2:
        raise ValueError("OSTC4 glyph height must be a positive even number")
    characters = sorted(set(args.characters), key=ord)
    if any(ord(character) < 0x80 for character in characters):
        raise ValueError("Only non-ASCII fallback glyphs belong in this font")
    font = ImageFont.truetype(str(args.font), args.font_size)

    declarations = []
    images = []
    entries = []
    preview = Image.new("L", (sum(max(1, math.ceil(font.getlength(c))) for c in characters), args.height), 0)
    preview_x = 0
    for character in characters:
        codepoint = ord(character)
        symbol = f"{args.name}_U{codepoint:04X}"
        width, data, image = render_glyph(font, character, args.height)
        declarations.append(
            f"static const uint8_t {symbol}_data[] __attribute__((section(\".lower_fonts.{symbol}_data\"))) = {{\n"
            f"{format_bytes(data)}\n}};\n"
            f"static const tImage {symbol} __attribute__((section(\".lower_fonts.{symbol}\"))) = "
            f"{{ {symbol}_data, {width}, {args.height} }};"
        )
        entries.append(f"    {{ 0x{codepoint:04X}, &{symbol} }}, /* {character} */")
        preview.paste(image, (preview_x, 0))
        preview_x += image.width
        images.append((character, width, len(data)))

    content = f"""/* Auto-generated by scripts/generate_chinese_font.py. Do not edit manually.
 * Source font: {args.font.name}
 * Glyph height: {args.height}; format: 8 bpp, column-major, empty-column marker 0x01.
 */
#include "gfx_fonts.h"

{chr(10).join(declarations)}

static const tChar {args.name}_array[] __attribute__((section(".lower_fonts.{args.name}_array"))) = {{
{chr(10).join(entries)}
}};

const tFont {args.name} __attribute__((used, section(".lower_font_directory.{args.name}"))) = {{
    {len(characters)}, {args.name}_array, {args.font_size // 2}, {args.font_size // 2}, {args.height}
}};
"""
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(content, encoding="utf-8")
    preview_path = args.output.with_suffix(".png")
    preview.save(preview_path)
    print(f"Generated {len(characters)} glyphs, {sum(item[2] for item in images)} bitmap bytes")
    print(f"Header: {args.output}")
    print(f"Preview: {preview_path}")


if __name__ == "__main__":
    main()
